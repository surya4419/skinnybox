export interface AppTarget {
  id: string;
  name: string;
  icon: string; // URL or emoji char
  type: 'SOCIAL' | 'GAME' | 'CUSTOM';
}

export interface Commitment {
  id: string;
  targetId: string;
  targetName: string;
  salt: string; // Stored locally, usually this would be separated in real backend
  hash: string;
  createdAt: number;
  expiryAt: number;
  epitaph: string; // Generated by Gemini
  isBuried: boolean;
}

export interface AppState {
  commitments: Commitment[];
  inventory: AppTarget[];
}

export enum ViewState {
  LANDING = 'LANDING',
  DASHBOARD = 'DASHBOARD',
  RITUAL = 'RITUAL',
  CERTIFICATE = 'CERTIFICATE',
  GLITCH_DEATH = 'GLITCH_DEATH'
}

export interface GeminiCurseResponse {
  epitaph: string;
  penaltyDescription: string;
}
